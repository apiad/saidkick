@pytest.mark.browser
async def test_tools_actually_drive_the_browser(engine, controller, fixture_url):
    """Descriptions aside, the wiring has to work."""
    mcp = build_mcp(engine, controller)
    ctx = await engine.open_context()
    tab = await ctx.open_tab(f"{fixture_url}/form.html")

    snap = await mcp.call_tool("snapshot_page", {"tab": tab.id})
    assert 'button "Send"' in str(snap)

    await mcp.call_tool("type", {"tab": tab.id, "text": "erin", "css": "#u"})
    await mcp.call_tool("click", {"tab": tab.id, "css": "#go"})
    text = await mcp.call_tool("snapshot_page", {"tab": tab.id, "mode": "text"})
    assert "submitted:erin" in str(text)


@pytest.mark.browser
async def test_request_human_tool_returns_a_relayable_message(engine, controller):
    mcp = build_mcp(engine, controller)
    ctx = await engine.open_context()
    out = await mcp.call_tool(
        "request_human",
        {"context": ctx.id, "reason": "solve the captcha", "deadline_s": 0.2, "poll_s": 0.1},
    )
    assert "solve the captcha" in str(out)
