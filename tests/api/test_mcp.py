import pytest

from saidkick.mcp_server import build_mcp

VS1_TOOLS = {
    "list_contexts",
    "open_context",
    "close_context",
    "list_tabs",
    "open_tab",
    "close_tab",
    "navigate",
    "snapshot_page",
    "find",
    "click",
    "type",
    "press",
    "select",
    "highlight",
    "screenshot",
    "get_events",
}
VS2_TOOLS = {"request_human", "control_state"}
VS4_TOOLS = {"list_pins", "read_pin"}
VS3_TOOLS = {"list_profiles", "save_profile"}


async def _descriptions(engine, controller):
    tools = await build_mcp(engine, controller).list_tools()
    return {t.name: t.description or "" for t in tools}


async def test_all_tools_registered(engine, controller):
    names = set(await _descriptions(engine, controller))
    assert names >= VS1_TOOLS
    assert names >= VS2_TOOLS
    assert names >= VS4_TOOLS
    assert names >= VS3_TOOLS


